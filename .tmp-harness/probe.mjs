import { chromium } from '/home/daytona/codebase/node_modules/playwright-core/index.mjs';
import { install } from './serve.mjs';
const browser = await chromium.launch({ headless: true, executablePath: '/home/daytona/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome', args: ['--no-sandbox','--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push('PAGEERROR: ' + e.message.slice(0,300)));
page.on('console', (m) => { if (m.type() === 'error') errors.push('CONSOLE: ' + m.text().slice(0,200)); });
await page.route('http://harness.local/**', await install());
await page.goto('http://harness.local/index.html', { waitUntil: 'load' });
await page.waitForTimeout(3000);
console.log('labels', await page.locator('[aria-label$="layer"]').evaluateAll((els) => els.map((e) => e.getAttribute('aria-label'))));
console.log('scroll', await page.evaluate(() => ({ sw: document.documentElement.scrollWidth, iw: window.innerWidth, sh: document.documentElement.scrollHeight, ih: window.innerHeight })));
console.log('canvas', await page.locator('[aria-label$="layer"]').first().boundingBox());
console.log('saved?', await page.evaluate(() => Boolean(window.__savedDesign)));
console.log('ERRORS', errors.slice(0,6));
await page.screenshot({ path: '/tmp/lamsa-harness/probe.jpg', type: 'jpeg', quality: 55 });
await browser.close();
